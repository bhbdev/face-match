import os
from pathlib import Path

DATABASE_URL = os.environ.get(
    "DATABASE_URL", "postgresql://facematch:facematch@localhost:5432/facematch"
)

DATA_DIR = Path(os.environ.get("DATA_DIR", "./data"))
HISTORIC_DIR = DATA_DIR / "historic"  # original/downloaded photos (+ .json sidecars)
CROPS_DIR = DATA_DIR / "crops"  # face crops generated by the indexer

# InsightFace model pack. buffalo_l = SCRFD detector + ArcFace (ResNet50), 512-d.
MODEL_NAME = os.environ.get("MODEL_NAME", "buffalo_l")
DET_SIZE = int(os.environ.get("DET_SIZE", "640"))
# Old photos are blurry and low contrast, so accept weaker detections than default (0.5).
DET_THRESH = float(os.environ.get("DET_THRESH", "0.4"))

# Convert images to grayscale before detection/embedding. Historic photos are
# black-and-white or sepia, so this narrows the gap between them and a modern
# color selfie. The index and the query should use the same setting.
GRAYSCALE = os.environ.get("GRAYSCALE", "1").lower() not in ("0", "false", "no", "")

MAX_UPLOAD_BYTES = int(os.environ.get("MAX_UPLOAD_MB", "15")) * 1024 * 1024
MAX_QUERY_SIDE = 1600  # downscale big phone photos before detection

EMBED_DIM = 512
